-- EventPass PostgreSQL baseline. New databases only; do not run against SQLite.
-- Store dates as ISO UTC text to preserve existing API contracts during migration.

CREATE TABLE IF NOT EXISTS schema_migrations (
  name TEXT PRIMARY KEY,
  applied_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE TABLE admins (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT NOT NULL,
 name TEXT NOT NULL,
 password_hash TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE UNIQUE INDEX admins_email_unique ON admins (lower(email));
CREATE TABLE sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 token_hash TEXT NOT NULL UNIQUE,
 admin_id BIGINT NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
 expires_at TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE INDEX sessions_admin_idx ON sessions(admin_id);
CREATE TABLE events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug TEXT NOT NULL UNIQUE,
 title TEXT NOT NULL,
 description TEXT NOT NULL DEFAULT '',
 location TEXT NOT NULL DEFAULT '',
 starts_at TEXT NOT NULL,
 ends_at TEXT NOT NULL,
 capacity INTEGER NOT NULL CHECK (capacity > 0),
 checkin_points INTEGER NOT NULL DEFAULT 10 CHECK (checkin_points >= 0),
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','closed')),
 created_by BIGINT NOT NULL REFERENCES admins(id),
 created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
 updated_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
 CHECK (ends_at >= starts_at)
);
CREATE TABLE participants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT NOT NULL,
 name TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE UNIQUE INDEX participants_email_unique ON participants (lower(email));
CREATE TABLE registrations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
 participant_id BIGINT NOT NULL REFERENCES participants(id),
 qr_token_hash TEXT NOT NULL UNIQUE,
 status TEXT NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed','cancelled')),
 created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
 UNIQUE (event_id,participant_id)
);
CREATE INDEX registrations_event_idx ON registrations(event_id);
CREATE TABLE checkins (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 registration_id BIGINT NOT NULL UNIQUE REFERENCES registrations(id) ON DELETE CASCADE,
 checked_in_by BIGINT NOT NULL REFERENCES admins(id),
 created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE TABLE point_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 participant_id BIGINT NOT NULL REFERENCES participants(id),
 checkin_id BIGINT NOT NULL UNIQUE REFERENCES checkins(id) ON DELETE CASCADE,
 points INTEGER NOT NULL CHECK (points >= 0),
 created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE INDEX point_entries_participant_idx ON point_entries(participant_id);
